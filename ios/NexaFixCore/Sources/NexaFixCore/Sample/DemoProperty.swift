    // MARK: Build

    private static func buildRoom(_ spec: RoomSpec, index: Int, count: Int, now: Date) -> Room {
        var extras = CaptureFixtures.Extras()
        extras.origin = spec.origin
        extras.objects = spec.objects
        extras.floorY = floorY
        extras.label = spec.name
        let fixture: CaptureFixtures.Fixture
        if let corners = spec.corners {
            fixture = CaptureFixtures.polygon(name: spec.name, corners: corners, height: ceiling, doors: spec.doors,
                                              windows: spec.windows, noise: .light, seed: spec.seed, extras: extras)
        } else {
            fixture = CaptureFixtures.rectangle(width: spec.width, depth: spec.depth, height: ceiling,
                                                doors: spec.doors, windows: spec.windows, noise: .light,
                                                seed: spec.seed, extras: extras)
        }
        // Rooms are scanned one after another, a few minutes apart, ending at `now`.
        let scannedAt = now.addingTimeInterval(-Double(count - 1 - index) * 420)
        var room = RoomBuilder.build(from: fixture.capture, name: spec.name, kind: spec.kind, now: scannedAt).room
        room.id = id("room." + spec.name)
        for v in spec.verifications { apply(v, to: &room, date: now) }
        addCustomMeasurements(for: spec, to: &room, now: now)
        return room
    }

    // MARK: Verification

    private static func rounded(_ x: Double) -> Double { (x * 1000).rounded() / 1000 }

    private static func nearestWall(in room: Room, to p: Point2) -> Int? {
        room.walls.indices.min { room.walls[$0].midpoint.distance(to: p) < room.walls[$1].midpoint.distance(to: p) }
    }

    private static func apply(_ v: Verify, to room: inout Room, date: Date) {
        func verify(_ m: inout Measured) {
            m.verify(rounded(m.scanned + v.delta), source: .laser, note: "\(syntheticNote): \(v.note)", date: date)
        }
        switch v.target {
        case .wall(let p):
            guard let i = nearestWall(in: room, to: p) else { return }
            if v.field == .height { verify(&room.walls[i].height) } else { verify(&room.walls[i].length) }
        case .window(let p), .door(let p):
            guard let w = nearestWall(in: room, to: p) else { return }
            let wallID = room.walls[w].id
            let wantWindow: Bool
            if case .window = v.target { wantWindow = true } else { wantWindow = false }
            guard let k = room.openings.firstIndex(where: { $0.wallID == wallID && ($0.kind == .window) == wantWindow }) else { return }
            switch v.field {
            case .width, .length: verify(&room.openings[k].width)
            case .height: verify(&room.openings[k].height)
            }
        }
    }

    // MARK: Custom measurements

    private static func addCustomMeasurements(for spec: RoomSpec, to room: inout Room, now: Date) {
        let h = floorY + 1.0
        switch spec.name {
        case "Master Bedroom":
            // The wardrobe run along the east wall, 1 m above the floor.
            let a = Point2(4.55, 6.2 + 0.3).world(elevation: h), b = Point2(4.55, 6.2 + 2.7).world(elevation: h)
            var m = CustomMeasurement(id: id("measurement.wardrobe"), label: "Wardrobe wall", a: a, b: b,
                                      createdAt: now, note: "Built-in wardrobe, floor to ceiling")
            m.length.verify(rounded(m.length.scanned + 0.006), source: .laser, note: "\(syntheticNote): Laser", date: now)
            room.customMeasurements.append(m)
        case "Kitchen":
            let a = Point2(6.2 + wallGap + 0.2, 2.75).world(elevation: h)
            let b = Point2(6.2 + wallGap + 3.0, 2.75).world(elevation: h)
            room.customMeasurements.append(CustomMeasurement(id: id("measurement.counter"), label: "Counter run",
                                                              a: a, b: b, createdAt: now))
        default:
            break
        }
    }
