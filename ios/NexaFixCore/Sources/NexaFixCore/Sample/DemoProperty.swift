import Foundation

/// A realistic, deterministic demo property for previews, screenshots and tests:
/// "Marina Gate 2 - Unit 2304", a two-bedroom apartment in Dubai Marina.
///
/// The rooms match `skills/nexa-costing/examples/2br-marina-full-fitout.yaml` (Living Room 6.2 x 4.5,
/// Kitchen 3.2 x 2.8, Master Bedroom 4.6 x 4.0, Bedroom 2 3.8 x 3.4, Corridor 5.0 x 1.4, Master
/// Bathroom 2.6 x 2.2, Bathroom 2 2.2 x 1.8) plus a 4.5 x 1.5 balcony, ceiling 2.8 m.
///
/// Every room goes through the real path: `CaptureFixtures` emits what RoomPlan would report
/// (shuffled, randomly flipped, a little scan noise) and `RoomBuilder.build` turns it into a `Room`.
/// The rooms share one floor frame (plan space, metres) and are separated by 0.15 m of wall
/// thickness, so they tile into a plausible apartment without overlapping:
///
///     y 12.55  +--------+
///              | M.Bath |
///     y 10.20  +--------+------------+
///              | Master  |  (B2 north)|
///              | Bedroom | Bedroom 2  |
///     y  6.2   +----+----+------------+
///        6.05  |  Corridor ---> entrance
///        4.65  +-------+------+-------+
///        4.50  |        Living |Bath 2 |
///              |               +-------+
///              |               |Kitchen|
///     y  0     +---------------+-------+
///                  [ Balcony ] below the living room
///
/// Dimensions are mostly unverified; a handful carry realistic laser checks (a few mm to 2 cm off the
/// scan), including the master bedroom wardrobe wall and the living room window, so the UI shows both
/// states. Bedroom 2's west wall leans, so its two west corners are about 91.4 and 88.4 degrees (the lean
/// is built in as 1.5 degrees; scan noise moves each corner by a fraction of a degree).
///
/// THE DEMO IS SELF-LABELLING. The laser "verifications" are fabricated so the UI can show both states, and
/// the reference looks like a real job number, so every place that could leak into a real document says so:
/// the reference starts with `DEMO-`, every `Verification.note` starts with `DemoProperty.syntheticNote`,
/// and `Property.notes` says it is not a real site. Nothing here is a measurement.
///
/// The Master Bedroom and Bedroom 2 are DELIBERATELY only about 10 cm apart at their closest (Bedroom 2's
/// west wall leans towards the master bedroom), tighter than the 12-20 cm between the other rooms. That is a
/// real-world squeeze the 3D wall builder has to cope with (`SceneGeometryTests` depends on it).
///
/// The furniture respects the rooms: nothing overlaps another piece (wall cabinets clear the refrigerator),
/// and nothing stands in a door's 0.8 m swing or access zone.
///
/// Everything is deterministic: identifiers are derived from fixed strings, the scan noise uses fixed
/// seeds, and `now` is injected.
public enum DemoProperty {

    /// Wall thickness between neighbouring rooms in the shared frame, metres.
    static let wallGap = 0.15
    static let ceiling = 2.8
    /// World Y of the floor in the (made-up) AR session frame.
    static let floorY = -1.30
    /// Prefix of the reference and of every verification note: the demo's numbers are not measurements.
    public static let syntheticNote = "DEMO - synthetic, not measured"
    /// Job reference of the demo; deliberately NOT a valid `NF-` number.
    public static let reference = "DEMO-NF-2026-1009-01"

    public static func make(now: Date = Date()) -> Property {
        let specs = roomSpecs()
        var rooms: [Room] = []
        for (index, spec) in specs.enumerated() {
            rooms.append(buildRoom(spec, index: index, count: specs.count, now: now))
        }
        let floor = Floor(id: id("floor.level23"), name: "Level 23", level: 23, rooms: rooms)
        return Property(id: id("property"), name: "Marina Gate 2 - Unit 2304", client: "Mr. Ahmed Khan",
                        address: "Marina Gate 2, Dubai Marina, Dubai", reference: reference,
                        kind: .apartment,
                        notes: "\(syntheticNote). Demo data: a scan generated by NexaFixCore, not a real site. "
                            + "The laser checks are made up.",
                        createdAt: now, updatedAt: now, floors: [floor])
    }

    // MARK: Identifiers

    static func id(_ key: String) -> UUID { RoomBuilder.stableUUID("NexaFix.Demo.MarinaGate2.Unit2304." + key) }

    // MARK: Room specs

    private struct Verify {
        enum Target {
            case wall(near: Point2)
            case window(nearWall: Point2)
            case door(nearWall: Point2)
        }
        enum Field { case length, width, height }
        var target: Target
        var field: Field
        /// Laser reading minus scan, metres (rounded to the millimetre when applied).
        var delta: Double
        var note: String
    }

    private struct RoomSpec {
        var name: String
        var kind: RoomKind
        /// South-west corner in the shared floor frame.
        var origin: Point2
        var width: Double
        var depth: Double
        /// Overrides the rectangle (room-local corners, counter-clockwise).
        var corners: [Point2]?
        var doors: [OpeningSpec] = []
        var windows: [OpeningSpec] = []
        var objects: [CaptureFixtures.FixtureObject] = []
        var seed: UInt64
        var verifications: [Verify] = []
    }

    private static func obj(_ category: String, _ x: Double, _ y: Double, w: Double, d: Double, h: Double,
                            yaw: Double = 0, elevation: Double = 0) -> CaptureFixtures.FixtureObject {
        CaptureFixtures.FixtureObject(category: category, center: Point2(x, y), yaw: yaw, width: w, depth: d,
                                      height: h, elevation: elevation)
    }

